public class PositionOffset {
    int dRow;
    int dCol;

    public PositionOffset() {
    }

    public PositionOffset(int dRow, int dCol) {
        this.dRow = dRow;
        this.dCol = dCol;
    }

    public int getdRow() {
        return dRow;
    }

    public void setdRow(int dRow) {
        this.dRow = dRow;
    }

    public int getdCol() {
        return dCol;
    }

    public void setdCol(int dCol) {
        this.dCol = dCol;
    }
}
