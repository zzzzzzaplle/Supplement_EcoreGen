public class FundingGroup {
    private String name;
    private FundingGroupType type;

    public FundingGroup() {
    }

    public String getName() {
        return this.name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public FundingGroupType getType() {
        return this.type;
    }

    public void setType(FundingGroupType type) {
        this.type = type;
    }
}
