import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.Date;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

/**
 * Represents a rented-car store that manages cars, rentals, and overdue notices.
 */
class Store {
    private String name;
    private List<Car> cars;
    private List<Rental> rentals;
    private List<OverdueNotice> notices;

    /**
     * Creates an empty store with initialized collections.
     */
    public Store() {
        this.cars = new ArrayList<>();
        this.rentals = new ArrayList<>();
        this.notices = new ArrayList<>();
    }

    /**
     * Identifies cars that are currently available in the store.
     * A car is available when it is not tied to an active rental whose back date is still empty.
     *
     * @return available cars in ascending order of daily price, or an empty list if none are available
     */
    public List<Car> identifyAvailableCars() {
        if (cars == null || cars.isEmpty()) {
            return new ArrayList<>();
        }

        List<Car> available = new ArrayList<>();
        for (Car car : cars) {
            if (car == null) {
                continue;
            }
            boolean isRentedActively = false;
            if (rentals != null) {
                for (Rental rental : rentals) {
                    if (rental == null || rental.getCar() == null) {
                        continue;
                    }
                    if (Objects.equals(car, rental.getCar()) && rental.getBackDate() == null) {
                        isRentedActively = true;
                        break;
                    }
                }
            }
            if (!isRentedActively) {
                available.add(car);
            }
        }

        available.sort(Comparator.comparingDouble(Car::getDailyPrice));
        return available;
    }

    /**
     * Calculates the total revenue generated by all rental records stored in the store.
     *
     * @return total revenue
     */
    public double calculateTotalRevenue() {
        double total = 0.0;
        if (rentals == null) {
            return total;
        }
        for (Rental rental : rentals) {
            if (rental != null) {
                total += rental.getTotalPrice();
            }
        }
        return total;
    }

    /**
     * Lists customers whose rentals are overdue.
     * A rental is overdue when its back date is empty and the current date is later than the due date.
     *
     * @param currentDate the current date
     * @return list of overdue customers, or an empty list when none exist or currentDate is null
     */
    public List<Customer> findCustomersWithOverdueRentals(Date currentDate) {
        if (currentDate == null || rentals == null || rentals.isEmpty()) {
            return new ArrayList<>();
        }

        List<Customer> overdueCustomers = new ArrayList<>();
        for (Rental rental : rentals) {
            if (rental == null) {
                continue;
            }
            Date dueDate = rental.getDueDate();
            if (rental.getBackDate() == null && dueDate != null && currentDate.after(dueDate)) {
                Customer customer = rental.getCustomer();
                if (customer != null && !overdueCustomers.contains(customer)) {
                    overdueCustomers.add(customer);
                }
            }
        }
        return overdueCustomers;
    }

    /**
     * Determines the average daily price of all cars stored in the store.
     *
     * @return average daily price, or 0.0 when there are no car records
     */
    public double determineAverageDailyPrice() {
        if (cars == null || cars.isEmpty()) {
            return 0.0;
        }

        double sum = 0.0;
        int count = 0;
        for (Car car : cars) {
            if (car != null) {
                sum += car.getDailyPrice();
                count++;
            }
        }
        return count == 0 ? 0.0 : sum / count;
    }

    /**
     * Counts how many rental records belong to each customer.
     *
     * @return a customer-to-count mapping, or an empty map when no rental records exist
     */
    public Map<Customer, Integer> countCarsRentedPerCustomer() {
        if (rentals == null || rentals.isEmpty()) {
            return new LinkedHashMap<>();
        }

        Map<Customer, Integer> result = new LinkedHashMap<>();
        for (Rental rental : rentals) {
            if (rental == null || rental.getCustomer() == null) {
                continue;
            }
            Customer customer = rental.getCustomer();
            result.put(customer, result.getOrDefault(customer, 0) + 1);
        }
        return result;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public List<Car> getCars() {
        return cars;
    }

    public void setCars(List<Car> cars) {
        this.cars = cars;
    }

    public void addCar(Car car) {
        if (this.cars == null) {
            this.cars = new ArrayList<>();
        }
        this.cars.add(car);
    }

    public List<Rental> getRentals() {
        return rentals;
    }

    public void setRentals(List<Rental> rentals) {
        this.rentals = rentals;
    }

    public void addRental(Rental rental) {
        if (this.rentals == null) {
            this.rentals = new ArrayList<>();
        }
        this.rentals.add(rental);
    }

    public List<OverdueNotice> getNotices() {
        return notices;
    }

    public void setNotices(List<OverdueNotice> notices) {
        this.notices = notices;
    }

    public void addNotice(OverdueNotice notice) {
        if (this.notices == null) {
            this.notices = new ArrayList<>();
        }
        this.notices.add(notice);
    }
}

/**
 * Represents a car in the store.
 */
class Car {
    private String plate;
    private String model;
    private double dailyPrice;

    /**
     * Creates an empty car.
     */
    public Car() {
    }

    public String getPlate() {
        return plate;
    }

    public void setPlate(String plate) {
        this.plate = plate;
    }

    public String getModel() {
        return model;
    }

    public void setModel(String model) {
        this.model = model;
    }

    public double getDailyPrice() {
        return dailyPrice;
    }

    public void setDailyPrice(double dailyPrice) {
        this.dailyPrice = dailyPrice;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Car)) return false;
        Car car = (Car) o;
        return Objects.equals(plate, car.plate);
    }

    @Override
    public int hashCode() {
        return Objects.hash(plate);
    }
}

/**
 * Represents a customer who rents cars.
 */
class Customer {
    private String name;
    private String surname;
    private String address;

    /**
     * Creates an empty customer.
     */
    public Customer() {
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getSurname() {
        return surname;
    }

    public void setSurname(String surname) {
        this.surname = surname;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Customer)) return false;
        Customer customer = (Customer) o;
        return Objects.equals(name, customer.name)
                && Objects.equals(surname, customer.surname)
                && Objects.equals(address, customer.address);
    }

    @Override
    public int hashCode() {
        return Objects.hash(name, surname, address);
    }
}

/**
 * Represents a rental record connecting a car and a customer.
 */
class Rental {
    private Date rentalDate;
    private Date dueDate;
    private Date backDate;
    private double totalPrice;
    private String leasingTerms;
    private Car car;
    private Customer customer;

    /**
     * Creates an empty rental record.
     */
    public Rental() {
    }

    public Date getRentalDate() {
        return rentalDate;
    }

    public void setRentalDate(Date rentalDate) {
        this.rentalDate = rentalDate;
    }

    public Date getDueDate() {
        return dueDate;
    }

    public void setDueDate(Date dueDate) {
        this.dueDate = dueDate;
    }

    public Date getBackDate() {
        return backDate;
    }

    public void setBackDate(Date backDate) {
        this.backDate = backDate;
    }

    public double getTotalPrice() {
        return totalPrice;
    }

    public void setTotalPrice(double totalPrice) {
        this.totalPrice = totalPrice;
    }

    public String getLeasingTerms() {
        return leasingTerms;
    }

    public void setLeasingTerms(String leasingTerms) {
        this.leasingTerms = leasingTerms;
    }

    public Car getCar() {
        return car;
    }

    public void setCar(Car car) {
        this.car = car;
    }

    public Customer getCustomer() {
        return customer;
    }

    public void setCustomer(Customer customer) {
        this.customer = customer;
    }
}

/**
 * Represents an overdue notice sent to a customer.
 */
class OverdueNotice {
    private String noticeId;
    private Customer customer;

    /**
     * Creates an empty overdue notice.
     */
    public OverdueNotice() {
    }

    public String getNoticeId() {
        return noticeId;
    }

    public void setNoticeId(String noticeId) {
        this.noticeId = noticeId;
    }

    public Customer getCustomer() {
        return customer;
    }

    public void setCustomer(Customer customer) {
        this.customer = customer;
    }

    /**
     * Sends a notice to a customer.
     *
     * @param customer target customer
     * @return a confirmation message
     */
    public String sendNoticeTo(Customer customer) {
        this.customer = customer;
        return "Overdue notice " + noticeId + " sent to " + (customer == null ? "unknown customer" : customer.getName() + " " + customer.getSurname());
    }
}