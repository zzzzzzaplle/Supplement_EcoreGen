"""
llm_codegen_test.py
Batch process FJC.java files generated by llm-codegen-javabench.py under LLM-pure-workspace:
  1. Compile with javac (FJC.java + projects/paXX-result/src/*.java)
  2. Run tests with JUnit ConsoleLauncher
  3. Output sample-level CSV reports and a global summary CSV

Usage:
    python3 llm_codegen_test.py
    # Edit BASE_DIRS, MODEL_NAMES, and SAMPLES below to control the run scope
"""

import csv
import re
import shutil
import subprocess
import sys
from datetime import datetime
from itertools import product
from pathlib import Path

# ============================================================
# Configuration
# ============================================================
SCRIPT_DIR = Path(__file__).parent
PROJECTS_DIR = SCRIPT_DIR.parent / "projects"   

# BASE_DIRS = ["pa19-result"]
BASE_DIRS = ["pa19-result", "pa20-result", "pa21-result", "pa22-result"]

MODEL_NAMES = ["deepseek-v4-flash","gpt-5.4-mini","minimax-m3"
,"gemini-3.1-flash-lite","qwen3.6-flash",
"deepseek-v4-flash-fix","gpt-5.4-mini-fix","minimax-m3-fix"
,"gemini-3.1-flash-lite-fix","qwen3.6-flash-fix"]
# MODEL_NAMES = ["deepseek-v4-flash", "deepseek-v4-flash-no-reason", "MiniMax-M2.7", "GLM-4.7"]

# SAMPLES = ["sample1", "sample2"]
SAMPLES = ["sample1", "sample2", "sample3", "sample4", "sample5"]

LIB_DIR = SCRIPT_DIR / "lib"
REPORT_DIR = SCRIPT_DIR / "test_reports"

# Compile and run timeouts (seconds)
COMPILE_TIMEOUT = 60
TEST_TIMEOUT = 180


# ============================================================
# Helper functions
# ============================================================

def _classpath_sep() -> str:
    return ";" if sys.platform == "win32" else ":"


def _get_full_classpath() -> str:
    """Get the full classpath for all jars in the lib directory."""
    sep = _classpath_sep()
    jars = sorted(LIB_DIR.glob("*.jar"))
    return sep.join(str(j) for j in jars)


def _get_proc_encoding() -> str:
    """Encoding for subprocess output: use GBK on Chinese Windows locales, otherwise UTF-8."""
    if sys.platform == "win32":
        import locale
        enc = locale.getpreferredencoding()
        if enc.lower() in ("cp936", "gbk", "gb2312", "gb18030"):
            return "gbk"
    return "utf-8"


def _run(cmd: list, timeout: int = 120) -> tuple:
    enc = _get_proc_encoding()
    result = subprocess.run(
        cmd, capture_output=True, text=True,
        encoding=enc, errors="replace",
        timeout=timeout,
    )
    return result.stdout, result.stderr, result.returncode


def _parse_junit_output(output: str) -> dict:
    """Extract test statistics from JUnit ConsoleLauncher output."""
    passed = failures = errors = skipped = 0

    m = re.search(r"\[\s*(\d+)\s*tests.\s+successful\s*\]", output, re.IGNORECASE)
    if m:
        passed = int(m.group(1))

    m = re.search(r"\[\s*(\d+)\s*tests.\s+failed\s*\]", output, re.IGNORECASE)
    if m:
        failures = int(m.group(1))

    m = re.search(r"\[\s*(\d+)\s*tests.\s+aborted\s*\]", output, re.IGNORECASE)
    if m:
        errors = int(m.group(1))

    m = re.search(r"\[\s*(\d+)\s*tests.\s+skipped\s*\]", output, re.IGNORECASE)
    if m:
        skipped = int(m.group(1))

    total = passed + failures + errors + skipped
    return {
        "passed": passed, "failures": failures,
        "errors": errors, "skipped": skipped, "total": total,
    }


def _ratio_str(passed: int, total: int) -> str:
    if total == 0:
        return "0.0000"
    return f"{passed / total:.4f}"


# ============================================================
# Single-sample compile and test flow
# ============================================================

CSV_FIELDS = [
    "system", "model", "sample",
    "compile_code", "compile_test",
    "total", "passed", "failed", "skipped",
    "pass_rate",
]


def run_sample(base_name: str, model: str, sample: str) -> dict:
    """Compile and test a single paXX-result/model/sample."""
    # Path definitions
    sample_dir = SCRIPT_DIR / base_name / model / sample
    fjc_path = sample_dir / "src" / "main" / "FJC.java"
    test_src_dir = PROJECTS_DIR / base_name / "src"
    classes_dir = sample_dir / "classes"

    row = {
        "system": base_name, "model": model, "sample": sample,
        "compile_code": "FAIL", "compile_test": "FAIL",
        "total": 0, "passed": 0, "failed": 0, "skipped": 0,
        "pass_rate": "0.0000",
    }

    # -- Check FJC.java --
    if not fjc_path.exists():
        msg = f"FJC.java not found: {fjc_path}"
        row["message"] = msg
        _save_compile_log(sample_dir, msg)
        return row

    # -- Check test code --
    if not test_src_dir.exists():
        msg = f"Test dir not found: {test_src_dir}"
        _save_compile_log(sample_dir, msg)
        return row

    test_files = sorted(test_src_dir.glob("*.java"))
    if not test_files:
        msg = f"No test .java files in {test_src_dir}"
        _save_compile_log(sample_dir, msg)
        return row

    # -- Step 1: Clear compilation artifacts --
    if classes_dir.exists():
        shutil.rmtree(classes_dir)
    classes_dir.mkdir(parents=True)

    compile_cp = _get_full_classpath()

    # -- Step 2: Compile functional code only (FJC.java) --
    code_cmd = [
        "javac", "-encoding", "UTF-8",
        "-J-Dfile.encoding=UTF-8",
        "-cp", compile_cp,
        "-d", str(classes_dir),
        str(fjc_path),
    ]

    stdout, stderr, rc = _run(code_cmd, timeout=COMPILE_TIMEOUT)
    compile_log = f"=== compile_code ===\nEXIT CODE: {rc}\n\n--- STDOUT ---\n{stdout}\n--- STDERR ---\n{stderr}\n"

    if rc != 0:
        # Functional code compilation failed
        _save_compile_log(sample_dir, compile_log)
        return row

    row["compile_code"] = "OK"

    # -- Step 3: Compile functional code plus test code --
    all_java_files = [str(fjc_path)] + [str(f) for f in test_files]
    test_compile_cmd = [
        "javac", "-encoding", "UTF-8",
        "-J-Dfile.encoding=UTF-8",
        "-cp", compile_cp,
        "-d", str(classes_dir),
    ] + all_java_files

    stdout2, stderr2, rc2 = _run(test_compile_cmd, timeout=COMPILE_TIMEOUT)
    compile_log += f"\n=== compile_test ===\nEXIT CODE: {rc2}\n\n--- STDOUT ---\n{stdout2}\n--- STDERR ---\n{stderr2}\n"
    _save_compile_log(sample_dir, compile_log)

    if rc2 != 0:
        # Test code compilation failed; functional code is OK
        return row

    row["compile_test"] = "OK"

    # -- Step 4: Run JUnit tests --
    sep = _classpath_sep()
    test_cp = f"{_get_full_classpath()}{sep}{classes_dir}"

    reports_dir = sample_dir / "test"
    reports_dir.mkdir(exist_ok=True)

    test_cmd = [
        "java", "-cp", test_cp,
        "org.junit.platform.console.ConsoleLauncher",
        "--scan-classpath",
        f"--classpath={classes_dir}",
        "--reports-dir", str(reports_dir),
    ]

    stdout, stderr, rc = _run(test_cmd, timeout=TEST_TIMEOUT)
    junit_out = (stdout or "") + ("\n" + stderr if stderr else "")

    # Save the test output log
    (sample_dir / "test_output.txt").write_text(
        f"EXIT CODE: {rc}\n\n--- STDOUT ---\n{stdout}\n--- STDERR ---\n{stderr}\n",
        encoding="utf-8",
    )
    (reports_dir / "junit-console.out.txt").write_text(
        junit_out, encoding="utf-8", errors="replace",
    )

    # -- Step 5: Parse results --
    stats = _parse_junit_output(junit_out)
    row.update({
        "total": stats["total"],
        "passed": stats["passed"],
        "failed": stats["failures"],
        "skipped": stats["skipped"],
        "pass_rate": _ratio_str(stats["passed"], stats["total"]),
    })

    # Save sample-level CSV
    sample_csv = reports_dir / "JAVAbench_report.csv"
    _write_csv(sample_csv, [row], CSV_FIELDS)

    return row


def _save_compile_log(sample_dir: Path, content: str):
    sample_dir.mkdir(parents=True, exist_ok=True)
    (sample_dir / "compile_result.txt").write_text(content, encoding="utf-8")


def _write_csv(path: Path, rows: list, fields: list) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


# ============================================================
# Main flow
# ============================================================

def main() -> None:
    # Check the lib directory
    jars = sorted(LIB_DIR.glob("*.jar")) if LIB_DIR.exists() else []
    if not jars:
        raise FileNotFoundError(f"No jars found in {LIB_DIR.resolve()}")

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    global_rows = []

    print(f"{'=' * 60}")
    print(f"  LLM-CodeGen Test Runner")
    print(f"{'=' * 60}")
    print(f"  Base dirs:   {BASE_DIRS}")
    print(f"  Models:      {MODEL_NAMES}")
    print(f"  Samples:     {SAMPLES}")
    print(f"  Lib jars:    {len(jars)}")
    print(f"  Input base:  {SCRIPT_DIR}")
    print(f"  Test source: {PROJECTS_DIR}")
    print(f"{'=' * 60}\n")

    for base_name, model in product(BASE_DIRS, MODEL_NAMES):
        model_base = SCRIPT_DIR / base_name / model
        if not model_base.exists():
            print(f"[SKIP] {base_name}/{model} not found")
            continue

        print(f"\n{'=' * 60}")
        print(f"  Project: {base_name}  Model: {model}")
        print(f"{'=' * 60}")

        sample_rows = []

        for sample in SAMPLES:
            print(f"  [{sample}] compiling & testing ...", end=" ", flush=True)
            row = run_sample(base_name, model, sample)
            print(f"compile={row['compile_code']}  test={row['compile_test']}  passed={row['passed']}/{row['total']}")
            sample_rows.append(row)

        # Save model-level CSV
        model_csv = SCRIPT_DIR / base_name / model / "model_report.csv"
        _write_csv(model_csv, sample_rows, CSV_FIELDS)
        print(f"  >> Model report: {model_csv}")

        # Write per-sample details to the global report
        global_rows.extend(sample_rows)

    # Save the global CSV
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    global_csv = REPORT_DIR / f"test_report_{timestamp}.csv"
    _write_csv(global_csv, global_rows, CSV_FIELDS)
    print(f"\n>> Global report: {global_csv}")
    print("Done.")


if __name__ == "__main__":
    main()
